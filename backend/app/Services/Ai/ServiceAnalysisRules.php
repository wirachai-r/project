<?php

namespace App\Services\Ai;

final class ServiceAnalysisRules
{
    public static function clarification(): string
    {
        return <<<'RULES'

ขั้นตอนวิเคราะห์สำหรับคำถามช่วย:
1. อ่าน question, detail และ answer_choices เพื่อระบุว่าคำถามเดิมต้องการแยกความแตกต่างเรื่องใด โดยยึดถ้อยคำและขอบเขตของคำถามเดิมเท่านั้น
2. ตรวจ assessment_context, user_message และ previous_clarifications ก่อนสร้างคำถาม แยกข้อมูลที่ทราบแล้ว ข้อมูลที่ยังไม่ชัด และข้อมูลที่ไม่เกี่ยวข้อง ห้ามถามข้อเท็จจริงที่ทราบแล้วแม้อยู่คนละส่วนของบริบท
3. เปรียบเทียบคำถามที่จะสร้างกับคำถามก่อนหน้าทั้งด้านถ้อยคำและความหมาย หากคำตอบที่เป็นไปได้ให้ข้อมูลเดิม ให้ตัดคำถามนั้นทิ้ง
4. เลือกเพียงประเด็นที่ยังไม่ทราบซึ่งช่วยแยก answer_choices ได้มากที่สุด และผู้ใช้สามารถสังเกตหรือตอบได้ด้วยตนเอง โดยไม่สร้างอาการ ตัวเลข ระยะเวลา หรือเกณฑ์ใหม่
5. ใช้คำตอบก่อนหน้าเพื่อตัดตัวเลือกที่ขัดกับข้อมูลที่ทราบ แต่ห้ามเลือกคำตอบหลักแทนผู้ใช้ หากข้อมูลยังไม่ชัดต้องคงทางเลือกที่ระบุไม่ได้
6. ตรวจครั้งสุดท้ายว่าคำถามสั้น มีหนึ่งประเด็น ตัวเลือกไม่ทับซ้อนกัน การจับคู่ตรงกับ answer_choices และไม่มีคำแนะนำหรือการวินิจฉัยแฝง
ให้ทำขั้นตอนเหล่านี้ภายในและส่งออกเฉพาะโครงสร้างที่ schema กำหนด ห้ามแสดงกระบวนการคิดภายใน
RULES;
    }

    public static function guidance(): string
    {
        return <<<'RULES'

ขั้นตอนวิเคราะห์สำหรับสรุปผลประเมิน:
1. สร้างภาพรวมจาก symptom, answered_questions และ clarification_observations ก่อน แล้วใช้ results ซึ่ง backend คำนวณแล้วเป็นข้อสรุปหลัก ห้ามคำนวณผลหรือระดับความเร่งด่วนใหม่
2. รวมคำตอบที่กล่าวถึงประเด็นเดียวกันเป็นข้อสังเกตเดียว แยกข้อมูลที่สนับสนุนผล ข้อมูลที่ไม่พบ และข้อมูลที่ยังไม่แน่ชัด โดยไม่ตีความคำตอบที่ไม่แน่ชัดเป็นการปฏิเสธ
3. หากข้อมูลคำตอบขัดกัน ให้ยึดผลจาก backend สำหรับ guidance และบรรยายเฉพาะข้อเท็จจริงที่ไม่ขัดกัน ห้ามเลือกข้อเท็จจริงฝ่ายใดเองเพื่อเปลี่ยนผล
4. เรียงเนื้อหาตามความสำคัญ: ความเร่งด่วนและสิ่งที่ควรทำ สัญญาณเตือน ภาพรวมอาการ การดูแลตนเอง และขั้นตอนถัดไป ห้ามให้รายละเอียดโรคกลบสิ่งที่ผู้ใช้ต้องทำ
5. เลือก self_care และ warning_signs เฉพาะข้อความต้นทางที่สัมพันธ์กับอาการหรือผลครั้งนี้ ตัดข้อความทั่วไป ข้อความซ้ำ และข้อความจากโรคหรือภาวะที่ไม่เกี่ยวข้อง
6. สรุปความไม่แน่นอนด้วยภาษาว่า “อาจเกี่ยวข้อง” หรือ “ผลประเมินระบุ” และห้ามขยายความเป็นความเป็นไปได้ใหม่ที่ไม่มีใน results
7. ตรวจว่ากรอบเวลา ความเร่งด่วน คำเตือน และ action ทุกข้อยังตรงกับข้อมูล backend ก่อนส่งออก
ให้ทำขั้นตอนเหล่านี้ภายในและส่งออกเฉพาะโครงสร้างที่ schema กำหนด ห้ามแสดงกระบวนการคิดภายใน
RULES;
    }

    public static function adaptiveGuidance(): string
    {
        return <<<'RULES'

ขั้นตอนวิเคราะห์สำหรับสรุปผลแบบปรับตามคำตอบ:
1. สรุป symptom และ answered_questions ตามข้อเท็จจริง โดยแยกคำตอบใช่ ไม่ใช่ และไม่แน่ใจออกจากกัน ห้ามตีความคำตอบไม่แน่ใจเป็นการปฏิเสธ
2. ใช้ results เป็นรายการภาวะที่ backend พบความสอดคล้องเท่านั้น ห้ามคำนวณ จัดระดับ หรือวินิจฉัยเพิ่ม และห้ามอ้างว่ารายการแรกมีโอกาสเป็นมากที่สุด
3. หากกล่าวถึงความสอดคล้อง ให้ใช้จำนวนอาการที่ส่งมาเท่านั้น ห้ามใช้เปอร์เซ็นต์ ความเสี่ยง ความน่าจะเป็น หรือคำว่ามีแนวโน้มเป็นโรค
4. ระบบนี้ไม่มีผลความเร่งด่วนจากแผนภูมิ ห้ามสรุปว่าปลอดภัย ไม่เร่งด่วน ควรพบแพทย์ภายในเวลาใด หรือไม่จำเป็นต้องพบแพทย์ เว้นแต่ข้อความนั้นมีอยู่โดยตรงใน disease_context.when_to_see_doctor
5. เลือก self_care และ warning_signs เฉพาะข้อความต้นทางที่สัมพันธ์กับอาการหรือภาวะใน results ตัดข้อความทั่วไปและข้อความซ้ำ หากไม่มีข้อมูลรองรับให้คืนรายการว่าง
6. ใช้ภาษาว่า “ภาวะที่มีอาการร่วมสอดคล้อง” และย้ำว่าเป็นข้อมูลประกอบจากคำตอบ ไม่ใช่การวินิจฉัยหรือการประเมินความน่าจะเป็น
7. ตรวจทุกข้อความย้อนกลับไปยังข้อมูลที่ส่งให้ก่อนส่งออก ห้ามนำความรู้ภายนอกมาเติม
ให้ทำขั้นตอนเหล่านี้ภายในและส่งออกเฉพาะโครงสร้างที่ schema กำหนด ห้ามแสดงกระบวนการคิดภายใน
RULES;
    }

    public static function healthTrend(): string
    {
        return <<<'RULES'

ขั้นตอนวิเคราะห์สำหรับแนวโน้มสุขภาพ:
1. ตรวจ period, counts และ dashboard_context เพื่อกำหนดขอบเขตเวลาและจำนวนข้อมูลก่อน ห้ามรายงานข้อมูลนอกช่วงหรือจำนวนที่ขัดกับข้อมูลสรุป
2. แยก assessments, follow_up_series และ daily_records เป็นคนละแหล่งหลักฐาน ห้ามนำคะแนนหรือสถานะคนละชนิดมารวมเป็นแนวโน้มเดียว
3. สำหรับแต่ละ follow_up_series ให้เรียงตามเวลาและเปรียบเทียบข้อมูลแรก ข้อมูลล่าสุด และข้อมูลระหว่างทาง เพื่อจำแนกเป็นดีขึ้น คงที่ แย่ลง ผันผวน หรือข้อมูลไม่พอ เฉพาะเมื่อข้อมูลรองรับ
4. ตรวจ assessments ตามเวลาเพื่อหาผลที่เกิดใหม่ เกิดซ้ำ หรือไม่ปรากฏในข้อมูลล่าสุด แต่ห้ามเรียกว่าโรคใหม่ โรคหาย หรือปลอดภัย
5. ใช้ daily_records เพื่อเสริมรูปแบบตามวันเท่านั้น หากข้อมูลไม่สม่ำเสมอหรือขัดกับแหล่งอื่น ให้บอกข้อจำกัดและไม่สรุปความสัมพันธ์เชิงเหตุผล
6. ให้น้ำหนักข้อมูลล่าสุดมากกว่าเมื่อเป็นข้อมูลชนิดเดียวกันและเกี่ยวข้องโดยตรง แต่ต้องกล่าวถึงการทรุดลงหรือสัญญาณเตือนแม้เกิดเพียงล่าสุด ห้ามให้ค่าเฉลี่ยกลบเหตุการณ์สำคัญ
7. เลือก observations ที่มีหลักฐานชัดและไม่ซ้ำกับ summary จากนั้นเลือก self_care และ warning_signs เฉพาะแหล่งที่อนุญาตและสัมพันธ์กับแนวโน้มที่พบ
8. ก่อนส่งออก ตรวจทุกข้อความย้อนกลับไปยังข้อมูลต้นทาง หากหาแหล่งรองรับไม่ได้ ให้ตัดข้อความนั้นออก หากข้อมูลไม่พอให้ระบุข้อจำกัดอย่างเฉพาะเจาะจง
ให้ทำขั้นตอนเหล่านี้ภายในและส่งออกเฉพาะโครงสร้างที่ schema กำหนด ห้ามแสดงกระบวนการคิดภายใน
RULES;
    }
}
