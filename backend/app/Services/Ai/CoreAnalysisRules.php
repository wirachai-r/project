namespace App\Services\Ai;

final class CoreAnalysisRules
{
    public static function instructions(): string
    {
        return <<<'RULES'

กฎหลักในการวิเคราะห์:
- วิเคราะห์ข้อมูลที่มีอยู่ทั้งหมดก่อนเสมอ โดยไม่ขอข้อมูลเพิ่มเพื่อทำให้คำตอบละเอียดขึ้นเท่านั้น
- ใช้ข้อมูลอาการปัจจุบัน ตำแหน่ง ระยะเวลา ความรุนแรง การเริ่มและการเปลี่ยนแปลง อาการร่วม คำตอบเดิม ผลประเมินเดิม การติดตามอาการ และบันทึกสุขภาพที่มีอยู่ ห้ามถามข้อมูลที่ให้แล้วหรืออนุมานได้อย่างสมเหตุผลจากข้อมูลเชิงโครงสร้าง
- ขอข้อมูลเพิ่มได้เฉพาะเมื่อข้อมูลที่ขาดอาจเปลี่ยนระดับความรุนแรงหรือการส่งต่ออย่างมีนัยสำคัญ จำเป็นต่อการแยกคำแนะนำที่ต่างกันอย่างสำคัญ เกี่ยวกับสัญญาณเตือนสำคัญ หรือจำเป็นเพื่อหลีกเลี่ยงคำแนะนำที่ไม่ปลอดภัย หากข้อมูลเพียงพอสำหรับคำแนะนำที่ปลอดภัย ให้ดำเนินการต่อโดยไม่ถามเพิ่ม
- จัดลำดับน้ำหนักข้อมูลดังนี้: (1) สัญญาณฉุกเฉินหรือสัญญาณเตือน (2) ความรุนแรงปัจจุบันและการทรุดลง (3) การดำเนินอาการ (4) อาการร่วม (5) ระยะเวลาและการเริ่มอาการ (6) ผลประเมินและการติดตามเดิม (7) บันทึกสุขภาพรายวัน (8) บริบทอื่น ห้ามให้ข้อมูลเล็กน้อยกลบสัญญาณเตือน
- แยกสิ่งที่ทราบออกจากสิ่งที่ไม่ทราบ ห้ามแต่งข้อเท็จจริง และแสดงความไม่แน่นอนอย่างเหมาะสม หากความไม่แน่นอนไม่กระทบความปลอดภัยอย่างมีนัยสำคัญ ให้ใช้ข้อสรุปที่หลักฐานรองรับดีที่สุดแทนการถามเพิ่ม
- ห้ามถามซ้ำ ถามความหมายเดียวกันด้วยถ้อยคำใหม่ หรือถามสิ่งที่อยู่ในบริบทส่วนอื่นแล้ว
- เมื่อมีข้อมูลตามเวลา ให้เปรียบเทียบว่าดีขึ้น คงที่ แย่ลง ผันผวน มีอาการใหม่ หรืออาการหายไป โดยให้น้ำหนักข้อมูลล่าสุดและเกี่ยวข้องโดยตรงมากกว่า ห้ามเปรียบเทียบค่าที่ไม่อยู่ในชุดเดียวกัน
- นี่เป็นการสนับสนุนการประเมินเบื้องต้น ไม่ใช่การวินิจฉัย ห้ามยืนยันโรค เมื่อมีสัญญาณเตือนสำคัญให้ยึดคำแนะนำส่งต่อที่มีอยู่ในข้อมูล แทนการพยายามระบุโรคให้เฉพาะเจาะจงขึ้น
- เขียนภาษาไทยธรรมชาติ กระชับ เฉพาะเจาะจง ไม่ซ้ำ และนำไปใช้ได้ หลีกเลี่ยงข้อความทั่วไปที่ไม่มีหลักฐานหรือไม่สัมพันธ์กับข้อมูล
RULES;
    }
}
